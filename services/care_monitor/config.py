# Значения справа — то, что действует при запуске из PyCharm.
# В аддоне Home Assistant их подменяет run.py через переменные окружения:
# ты правишь настройки в интерфейсе аддона, файл трогать не нужно.

import json
import os


def _text(name, default):
    return os.environ.get(name, default)


def _number(name, default):
    try:
        return type(default)(os.environ[name])
    except (KeyError, ValueError, TypeError):
        return default


def _flag(name, default):
    value = os.environ.get(name)
    return default if value is None else value.strip().lower() in ("1", "true", "yes", "on")


def _json(name, default):
    raw = os.environ.get(name)
    if not raw:
        return default
    try:
        return json.loads(raw)
    except ValueError:
        return default


def _list(name, default):
    raw = os.environ.get(name)
    if raw is None:
        return default
    items = [part.strip() for part in raw.split(",") if part.strip()]
    return items or None


