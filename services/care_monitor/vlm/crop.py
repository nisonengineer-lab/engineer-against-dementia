"""Прямоугольник кадра, в котором находится наблюдаемый.

ЗАЧЕМ. Камеры снимают 2880x1620 с широким углом. Человек занимает в таком
кадре десятую часть ширины — а вопросы к модели все до одного про мелочи:
сидит или лежит, держится ли за стену, свесилась ли голова, упал или сел
сам. По кадру, где человек размером с ноготь, на них честно не ответить, и
модель начинает додумывать.

Поэтому кадры режутся по человеку. Геометрию даёт Frigate: рамку объекта в
долях кадра и след — где он был в каждый момент события.

ОДИН ПРЯМОУГОЛЬНИК НА ВСЁ СОБЫТИЕ, а не свой на каждый кадр. Так это
остаётся одним вызовом ffmpeg вместо дюжины, и — что важнее — так оно само
делает то, что нужно:

    человек сидел на месте  -> след короткий, прямоугольник тесный,
                               человек виден крупно
    человек шёл через двор  -> след длинный, прямоугольник широкий,
                               видно и его, и путь, и обстановку

То есть там, где вопрос про мелкие признаки (поза, сон, еда, падение),
получается крупный план, а там, где вопрос про перемещение (походка), —
общий. Ровно так, как и надо.

ЗАПАС ВОКРУГ. Впритык по рамке резать нельзя: пропадает опора, на которую
он опирается, мебель, под которую он садится, пол, на котором он оказался.
Берём процент от размера самого прямоугольника плюс небольшой пол в долях
кадра — чтобы запас не исчезал, когда человек далеко и рамка крошечная.
"""
import logging

import config

log = logging.getLogger("crop")


def region_for(points, box):
    """Прямоугольник (x, y, w, h) в долях кадра. None — резать не по чему.

    points — след наблюдаемого, [(x, y, время)] в долях кадра
    box    — его рамка, (x, y, w, h) в долях кадра

    Из рамки берём только РАЗМЕР: где он был в каждый момент, точнее говорит
    след. В следе X — это центр рамки, а Y — её НИЗ, ноги.

    Ни то, ни другое не привязано к объекту события: те же две величины
    приходят и при живом разборе, и при переоценке старой записи.
    """
    if not config.CROP or not box or not points:
        return None

    _, _, bw, bh = box
    half = bw / 2

    left = min(x for x, _, _ in points) - half
    right = max(x for x, _, _ in points) + half
    bottom = max(y for _, y, _ in points)
    top = min(y for _, y, _ in points) - bh

    # Запас: процент от уже получившегося размера, но не меньше пола.
    pad_x = max((right - left) * config.CROP_PAD / 100, config.CROP_PAD_MIN)
    pad_y = max((bottom - top) * config.CROP_PAD / 100, config.CROP_PAD_MIN)

    left -= pad_x
    right += pad_x
    top -= pad_y
    bottom += pad_y

    # Слишком тесный прямоугольник модели не помогает, а мешает: пропадает
    # всё, по чему видно обстановку. Растягиваем от центра до минимума.
    left, right = _at_least(left, right, config.CROP_MIN)
    top, bottom = _at_least(top, bottom, config.CROP_MIN)

    left, right = _inside(left, right)
    top, bottom = _inside(top, bottom)

    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return None
    if w > 0.98 and h > 0.98:
        return None                 # это и есть целый кадр, резать нечего
    return left, top, w, h


def _at_least(low, high, minimum):
    """Растянуть отрезок до минимальной длины, не сдвигая центра."""
    gap = minimum - (high - low)
    if gap <= 0:
        return low, high
    return low - gap / 2, high + gap / 2


def _inside(low, high):
    """Вернуть отрезок в кадр, сохранив длину, насколько это возможно."""
    length = min(high - low, 1.0)
    if low < 0:
        low = 0.0
    if low + length > 1.0:
        low = 1.0 - length
    return low, low + length


def ffmpeg_filter(region):
    """Фильтр crop для ffmpeg. Доли, а не пиксели: они верны для любого
    разрешения, а detect-поток Frigate и записанный клип разного размера."""
    if not region:
        return None
    x, y, w, h = region
    # trunc(...*2)*2 — размеры должны быть чётными, иначе кодек ругается.
    return (f"crop=w=trunc(iw*{w:.4f}/2)*2:h=trunc(ih*{h:.4f}/2)*2"
            f":x=trunc(iw*{x:.4f}):y=trunc(ih*{y:.4f})")
