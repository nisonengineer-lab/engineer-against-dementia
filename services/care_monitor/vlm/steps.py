    # кадра» — в обрезанном по человеку кадре ни того, ни другого нет:
    # проём остаётся за вырезом, а за край человек уходит всегда, потому
    # что край выреза идёт за ним следом. Поэтому здесь кадры целиком.
    Step("toilet_in", "зашёл в туалет", _left_into_toilet, _apply_toilet_in,
         frames="last", wide=True, hint=_hint_toilet_in),

    Step("toilet_out", "вышел из туалета", _came_out_of_toilet, _apply_toilet_out,
         frames="first", wide=True, hint=_hint_toilet_out),
