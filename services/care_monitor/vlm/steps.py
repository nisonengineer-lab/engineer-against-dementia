"""Цепочка отдельных запросов к модели.

Один большой вопрос «расскажи всё сразу» модель отвечает расплывчато: она
усредняет и теряет детали. Поэтому каждый вопрос задаётся ОТДЕЛЬНЫМ запросом
и только тогда, когда датчики Frigate дают повод его задать.

Порядок такой:
    проверка         — есть ли наблюдаемый на кадрах вообще (всегда, отдельно)
    падение          — ВСЕГДА: упал или нет. Один вопрос, два ответа
    походка          — если датчики говорят, что он шёл
    поза             — всегда: в каких положениях он побывал
    еда              — если сидел или стоял
    сон              — если сидел или лежал
    туалет (вход)    — если последняя зона маршрута — вход в туалет
    туалет (выход)   — если первая зона маршрута — вход в туалет

Порядок внутри цепочки собран по НАБОРУ КАДРОВ, а не только по смыслу:
сначала все вопросы по всем кадрам, потом по последним, потом по первым.
Ollama переиспользует уже посчитанные картинки, пока следующий запрос идёт
по тем же кадрам, и это разница между 28 секундами и тремя.

ПАДЕНИЕ СПРАШИВАЕТСЯ ПЕРВЫМ И ВСЕГДА. Раньше оно висело на позе: сначала
модель решала, лежит он или сидит, и только потом, если «лежит», её
спрашивали про падение. Значит ошибка в позе прятала падение целиком — самое
дорогое, что эта система вообще должна замечать. Теперь это отдельный вопрос,
ни от чего не зависящий, и ответов у него ровно два: упал или нет.

ШАГА «ЧТО ДЕЛАЕТ» БОЛЬШЕ НЕТ. Он просил модель описать действие своими
словами и выдавал абзацы вроде «сидит, держит что-то в руках, взгляд
направлен вперёд, тело слегка сутулится». Ни одно решение системы на этом не
строилось, в карточке это не показывается, а запрос был самым дорогим в
цепочке — двенадцать кадров ради текста, который никто не читает.

Ответ каждого шага дописывается в одну карточку, и следующий шаг видит её
уже дополненной: позы, найденные шагом «поза», решают, спрашивать ли про сон,
еду и падение.

ПОЗА — ЭТО СПИСОК, А НЕ ОДНО СЛОВО. Событие длится минуты, и за них человек
успевает войти, постоять, сесть, снова встать. Раньше поза была одним словом,
и это ломало половину цепочки: если датчики видели движение, поза становилась
«идёт», шаг «поза» вообще не задавался, а за ним отваливались и сон, и еда, и
падение — их условия смотрели на то самое единственное слово. Восемнадцать
минут, за которые человек походил, посидел и снова походил, оставались в
журнале как «поза: идёт».

Теперь шаг «поза» задаётся ВСЕГДА и возвращает последовательность:
card["postures"] — список по порядку времени, card["posture"] — то, в чём он
остался под конец (его и пишем в базу, по нему считается вид события и «где
он сейчас»). Условия следующих шагов смотрят на СПИСОК: посидел хоть раз —
спросим и про сон, и про еду.
"""
import config


class Step:
    """Один вопрос к модели.

    name      — короткое имя, оно же имя файла промпта и ключ в логах
    title     — как шаг называется в журнале
    when      — (person, card) -> bool: задавать ли вопрос вообще
    apply     — (card, answer) -> None: куда положить ответ
    frames    — какие кадры показать: "all", "spread", "last", "first"
    reference — прикладывать ли эталонные фото наблюдаемого
    memory    — рассказывать ли, где его видели в прошлый раз
    heavy     — задавать ли этот вопрос тяжёлой модели (VLM_VALIDATE_MODEL)
    wide      — смотреть кадры ЦЕЛИКОМ, без кропа по человеку
    hint      — (person, card) -> список строк, дописываемых в ФАКТЫ
    """

    def __init__(self, name, title, when, apply, frames="all",
                 reference=False, memory=True, heavy=False, wide=False,
                 hint=None):
        self.name = name
        self.title = title
        self.when = when
        self.apply = apply
        self.frames = frames
        self.reference = reference
        self.memory = memory
        self.heavy = heavy
        self.wide = wide
        self.hint = hint

    @property
    def prompt_file(self):
        return f"{self.name}.txt"

    def needed(self, person, card):
        if self.name in config.STEPS_OFF:
            return False
        return bool(self.when(person, card))

    def facts(self, person, card):
        return list(self.hint(person, card)) if self.hint else []

    def __repr__(self):
        return f"Step({self.name})"


# ---------- как читать датчики ----------

def is_moving(person):
    """Шёл ли человек. Берём длину пути без рывков трекера: время в path_data
    идёт и когда человек стоит, а вот путь при этом не растёт."""
    return person.clean_length >= config.MOVING_MIN_PATH or person.is_wandering


def first_zone(person):
    route = person.zone_route_list
    return route[0] if route else None


def last_zone(person):
    route = person.zone_route_list
    return route[-1] if route else None


def zone_name(zone):
    return config.ZONE_NAMES.get(zone, zone) if zone else None


def _zones(person):
    return set(person.zone_route_list)


def near_bed_or_sofa(person):
    """Он там, где люди ложатся: сама кровать, сам диван или комната с ними."""
    zones = _zones(person)
    return bool(zones & set(config.BED_ZONES + config.SOFA_ZONES
                            + config.SLEEP_ROOM_ZONES))


def lying_place(person):
    """Что под ним по данным зон — подсказка для шагов про сон и падение."""
    zones = _zones(person)
    if zones & set(config.BED_ZONES):
        return "кровать"
    if zones & set(config.SOFA_ZONES):
        return "диван"
    return None


def lying_place_where(person):
    """То же, но в форме «на кровати» — для строки о том, почему тревоги нет."""
    place = lying_place(person)
    return {"кровать": "на кровати", "диван": "на диване"}.get(place, "на месте")


# ---------- условия шагов ----------

def _always(person, card):
    return True


def _walked(person, card):
    return card.get("moving")


def postures_of(card):
    """Все положения за событие. Одно слово в card["posture"] — это лишь то,
    в чём он остался; условия шагов должны смотреть на весь список."""
    seen = list(card.get("postures") or [])
    last = card.get("posture")
    if last and last != "не видно" and seen[-1:] != [last]:
        seen.append(last)
    return seen


def _was(card, *what):
    return bool(set(postures_of(card)) & set(what))


def _sat_or_lay(person, card):
    """Спрашивать ли про сон.

    Зону убрали намеренно. Раньше условие требовало, чтобы человек был возле
    кровати или дивана, — и дрёма в кресле у стола или на стуле в кухне не
    проверялась вовсе. Пожилые спят сидя где угодно, и это как раз то, что
    важно заметить: заснул сидя — значит устал или ему нехорошо.

    Зона не потеряна: она уходит в подсказку, чтобы модель знала, где он.
    """
    return _was(card, "лежит", "сидит")


def _sat_or_stood(person, card):
    """Спрашивать ли про еду. Достаточно, чтобы он ХОТЬ РАЗ за событие сел
    или встал на месте: едят сидя, но и стоя у стола тоже."""
    return _was(card, "сидит", "стоит")


def _toilet_at_end(person):
    """Зона туалета в КОНЦЕ маршрута — похоже на вход.

    Смотрим не только на самую последнюю зону, но и на предпоследнюю.
    Раньше условие требовало, чтобы туалет был ровно последним, — и это
    молча теряло самый обычный случай: человек дошёл до двери, а событие
    закончилось, когда он уже вернулся в зал. Маршрут выглядел как
    «зал → вход в туалет → зал», последняя зона — зал, вопрос не
    задавался вовсе, и в карточке про туалет не оставалось ни слова.

    Две зоны, а не больше: этого хватает, чтобы поймать «дошёл и
    вернулся в кадр», и мало, чтобы принять за поход в туалет обычный
    проход мимо двери в начале длинного события.

    Смотрим на ПОСЛЕДНЕЕ появление зоны туалета в маршруте. Если оно же
    и первое — он из туалета вышел, а не вошёл, и вопрос не наш. Но если
    туалет встречается ещё раз в конце («туалет → зал → туалет»), то он
    вышел и зашёл снова, и вход спросить надо. Маршрут из одной зоны —
    случай без порядка: спрашиваем и про вход, и про выход.
    """
    route = person.zone_route_list
    spots = [i for i, zone in enumerate(route) if zone in config.TOILET_ZONES]
    if not spots:
        return False
    last = spots[-1]
    if last < len(route) - 2:
        return False                    # туалет остался далеко позади
    return last > 0 or len(route) == 1


def _toilet_at_start(person):
    """Зона туалета ПЕРВОЙ в маршруте — похоже на выход."""
    route = person.zone_route_list
    return bool(route) and route[0] in config.TOILET_ZONES


def _left_into_toilet(person, card):
    return _toilet_at_end(person)


def _came_out_of_toilet(person, card):
    return _toilet_at_start(person)


def toilet_by_zone(person):
    """Что о туалете говорят ОДНИ ТОЛЬКО ДАТЧИКИ, без модели.

    Нужно на случай, когда модель входа на кадрах не увидела. Она может
    ошибиться, кадр может быть тёмным, дверь может оказаться за краем —
    но зона Frigate сработала, и это факт, а не мнение. Терять его
    нельзя: именно из-за этого карточка похода в туалет оставалась
    пустой, хотя сам поход человек видел своими глазами.

    Формулировка осторожная — «у двери»: датчики знают, что он там был,
    и не знают, вошёл ли он внутрь. Слово «зашёл» по-прежнему говорит
    только модель.

    Срабатывает ровно там, где мы и спрашиваем модель. Иначе отметка
    вешалась бы на каждый проход мимо двери.
    """
    if _toilet_at_end(person) or _toilet_at_start(person):
        return "у двери"
    return None


# ---------- подсказки в ФАКТЫ ----------

def _hint_sleep(person, card):
    lines = [f"ПОЛОЖЕНИЯ ЗА СОБЫТИЕ: {_postures_line(card)}",
             f"ДАТЧИКИ: не двигался {person.still_seconds} с "
             f"из {person.duration} с"]
    place = lying_place(person)
    if place:
        lines.append(f"ЗОНА ГОВОРИТ, что рядом {place} — там обычно и спят")
    elif near_bed_or_sofa(person):
        lines.append("ЗОНА ГОВОРИТ, что он в комнате, где спят")
    else:
        lines.append("ЗОНА КРОВАТИ И ДИВАНА НЕ СРАБОТАЛА — если он спит, "
                     "то не в постели, а там, где сидел")
    lines.append("ПРОВЕРЬ ПРЕДПОЛОЖЕНИЕ: он спит")
    return lines


def _hint_fall(person, card):
    """Только факты датчиков, без наводок.

    Здесь стояло «ЗОНА КРОВАТИ И ДИВАНА НЕ СРАБОТАЛА — если он внизу, то,
    скорее всего, на полу». Это не факт, а подсказка ответа, и модель
    отвечает такой подсказкой, а не тем, что видит. Вопрос про падение
    единственный, где цена ошибки — поднятый среди ночи человек, и
    подталкивать в нём нельзя ни в одну сторону.

    Зато полезно сказать, насколько кадры редкие: промпт запрещает судить о
    резкости, и число подтверждает, что судить по ним и правда нечем.
    """
    gap = (person.duration or 0) / max(config.FRAMES_PER_EVENT, 1)
    lines = [f"ДАТЧИКИ: событие длилось {person.duration} с, "
             f"не двигался {person.still_seconds} с",
             f"КАДРЫ: между соседними около {gap:.0f} с"]
    place = lying_place(person)
    if place:
        lines.append(f"ЗОНА: рядом {place}. Это значит «рядом», а не «под ним»")
    return lines


_WHOLE_FRAME = ("КАДРЫ ЦЕЛИКОМ: это полный кадр камеры, а не вырезка по "
                "человеку. Значит краю кадра можно верить: край здесь — это "
                "граница комнаты, а не граница выреза.")


def _hint_toilet_in(person, card):
    return [f"ДАТЧИКИ: маршрут по зонам — {person.zone_route or 'вне зон'}",
            f"ДАТЧИКИ: последняя зона маршрута — {zone_name(last_zone(person))}",
            _WHOLE_FRAME,
            "ПРОВЕРЬ ПРЕДПОЛОЖЕНИЕ: он зашёл в туалет"]


def _hint_toilet_out(person, card):
    return [f"ДАТЧИКИ: маршрут по зонам — {person.zone_route or 'вне зон'}",
            f"ДАТЧИКИ: первая зона маршрута — {zone_name(first_zone(person))}",
            _WHOLE_FRAME,
            "ПРОВЕРЬ ПРЕДПОЛОЖЕНИЕ: он вышел из туалета"]


def _hint_gait(person, card):
    lines = [f"ДАТЧИКИ: он перемещался, путь {person.clean_length} доли кадра, "
             f"смещение {person.displacement}, темп {person.frame_speed} кадра/с",
             f"НАПРАВЛЕНИЕ: {person.heading_text}"]
    if person.is_wandering:
        lines.append("ДАТЧИКИ: путь длинный, а смещение малое — похоже на топтание "
                     "на месте, проверь это глазами")
    return lines


def _postures_line(card):
    seen = postures_of(card)
    return " -> ".join(seen) if seen else "пока не определены"


def _hint_posture(person, card):
    """Шаг задаётся всегда, поэтому подсказка должна честно сказать, что
    датчики видели: и «шёл», и «стоял» — это разные наводки."""
    lines = [f"ДАТЧИКИ: событие длилось {person.duration} с, из них он "
             f"не двигался {person.still_seconds} с, шёл {person.path_seconds} с"]
    if card.get("moving"):
        lines.append("ДАТЧИКИ: перемещение было — но за длинное событие он "
                     "мог и походить, и посидеть. Смотри все кадры, а не один")
    else:
        lines.append("ДАТЧИКИ: перемещения не было — он оставался на одном месте")
    if card.get("gait_walks") is False:
        lines.append("МОДЕЛЬ ВЫШЕ СКАЗАЛА, что на самом деле он не шёл")
    lines.append(f"ГЕОМЕТРИЯ РАМКИ подсказывает «{person.posture}», "
                 f"но это лишь пропорции прямоугольника — верь глазам")
    return lines


def _hint_meal(person, card):
    return [f"ПОЛОЖЕНИЯ ЗА СОБЫТИЕ: {_postures_line(card)}",
            "ПРОВЕРЬ ПРЕДПОЛОЖЕНИЕ: он ест или пьёт"]


# ---------- куда класть ответы ----------

def _apply_validate(card, answer):
    card["subject_found"] = bool(answer.get("subject_found"))
    card["match"] = answer.get("match")
    card["people_in_frame"] = answer.get("people_in_frame")
    card["quality"] = answer.get("quality")


def _add_posture(card, name, front=False):
    """Дописать положение с краю списка.

    Отбрасываем только СОСЕДНИЙ повтор. Повтор через другое положение —
    «постоял, посидел, снова встал» — это и есть та смена, ради которой
    список заводился, и терять её нельзя.
    """
    if not name or name == "не видно":
        return
    seen = list(card.get("postures") or [])
    if front:
        if seen[:1] == [name]:
            return
        seen.insert(0, name)
    else:
        if seen[-1:] == [name]:
            return
        seen.append(name)
    card["postures"] = seen


# Положений ровно четыре, других не бывает. «Наклонился», «на корточках»,
# «ползёт» убраны: за ними шла возня с оттенками, а решение — «он на ногах
# или он завалился» — от них не зависело.
POSTURES = ("идёт", "стоит", "сидит", "лежит")


def _clean_postures(answer):
    """Список от модели: только известные слова, без соседних повторов.

    Модель иногда возвращает ["сидит","сидит","сидит"] по числу кадров или
    вписывает туда действие вместо положения. Список — это смена положений,
    а не протокол покадрово."""
    known = POSTURES
    out = []
    for item in answer.get("postures") or []:
        name = str(item).strip().lower()
        if name in known and (not out or out[-1] != name):
            out.append(name)
    return out


def _apply_gait(card, answer):
    card["gait_walks"] = answer.get("walks")
    card["gait"] = answer.get("gait")
    card["gait_support"] = answer.get("support")
    card["gait_risk"] = answer.get("risk")
    card["gait_note"] = answer.get("note")
    if answer.get("walks"):
        # Шаг походки идёт первым, поэтому «идёт» встаёт в начало списка.
        # Дальше шаг позы допишет туда всё остальное, что он увидел.
        _add_posture(card, "идёт", front=True)
        card.setdefault("posture", "идёт")


def _apply_posture(card, answer):
    """Позы за событие списком плюс та, в которой он остался.

    card["posture"] — КОНЕЧНОЕ положение, а не главное. Именно оно уходит в
    базу, в «где он сейчас» и в расчёт вида события: вопрос «что с ним
    сейчас» важнее, чем «что было в середине». Всё, что было по дороге,
    лежит в card["postures"], и по нему решают, спрашивать ли про сон и еду.
    """
    seen = _clean_postures(answer)
    if seen:
        # Список от этого шага ЗАМЕНЯЕТ предварительный, а не дописывается к
        # нему. Шаг походки успел положить туда «идёт», но он знает только,
        # что движение было, — когда именно, знает лишь тот, кто смотрел все
        # кадры по порядку. Иначе «сидел, потом пошёл» превращалось в
        # «пошёл, потом сидел».
        card["postures"] = seen
        if card.get("gait_walks") and "идёт" not in seen:
            # Датчики и походка движение видели, а этот шаг его не назвал.
            # Не выбрасываем: ход был, просто модель описала стоянки.
            _add_posture(card, "идёт", front=True)

    last = (answer.get("posture") or "").strip().lower()
    if last and last != "не видно":
        _add_posture(card, last)
        card["posture"] = last
    elif card.get("postures"):
        card["posture"] = card["postures"][-1]
    else:
        card.setdefault("posture", "не видно")

    # on_what этот шаг НЕ трогает. Раньше он спрашивал «на чём», модель была
    # обязана что-то ответить и выдумывала мебель: человек полулежал на
    # кровати, а в карточке стояло «сидит на стуле». На чём он лежит,
    # спрашивает шаг падения — там это и вправду нужно: пол или кровать
    # решают, тревога это или отдых.
    card["posture_sure"] = answer.get("sure")
    card["posture_note"] = answer.get("note")


def _apply_sleep(card, answer):
    """Кроме «спит/не спит» запоминаем, шевелился ли он.

    Лежать и бодрствовать — не то же самое, что спать, и не то же самое,
    что «не спит» у сидящего. Человек, который лежит и двигает руками,
    это отдельное состояние, и его надо видеть в журнале, а не выводить
    из отсутствия отметки о сне."""
    card["sleeping"] = bool(answer.get("sleeping"))
    card["sleep_moves"] = answer.get("moves")
    card["sleep_sure"] = answer.get("sure")
    card["sleep_head"] = answer.get("head")
    card["sleep_note"] = answer.get("note")


def _apply_fall(card, answer):
    """Ровно одно поле и два значения: упал или нет.

    Ни поверхности, ни своей оценки опасности, ни «пытается ли встать», ни
    даже фразы своими словами. Каждое лишнее поле в ответе — это ещё одна
    вещь, которую модель обдумывает вместо главного вопроса, и ещё один
    повод ответить расплывчато. Уровень тревоги всё равно считает код."""
    card["fallen"] = bool(answer.get("fallen"))


def _apply_meal(card, answer):
    """Два формата ответа. Простой промпт (2.6.0) просит выбрать одно из
    трёх — {"doing": "ест / пьёт / ничего»}: маленькой модели выбор из
    вариантов даётся лучше, чем три отдельных «да/нет». Старый формат с
    полями eating/drinking/meds по-прежнему понимается — промпт в /share
    мог остаться прежним."""
    if "doing" in answer:
        doing = str(answer.get("doing") or "").strip().lower()
        card["eating"] = doing == "ест"
        card["drinking"] = doing == "пьёт"
        card["meds"] = False
    else:
        card["eating"] = bool(answer.get("eating"))
        card["drinking"] = bool(answer.get("drinking"))
        card["meds"] = bool(answer.get("meds"))
    card["meal_items"] = answer.get("items") or []
    card["meal_note"] = answer.get("note")


def _apply_toilet_in(card, answer):
    """Ответ запоминаем ВСЕГДА, а не только когда он «да».

    Раньше при ответе «не заходил» в карточке не оставалось ничего:
    ни отметки, ни следа того, что вопрос вообще задавали. На экране это
    выглядело так же, как «мы не спрашивали», и человек, своими глазами
    видевший поход в туалет, не мог понять, ошиблась модель или шаг
    пропустили. Теперь ответ «нет» — тоже ответ, и он виден."""
    card["toilet_in"] = bool(answer.get("entered"))
    if answer.get("entered"):
        card["toilet"] = "зашёл"
    card["toilet_in_sure"] = answer.get("sure")
    card["toilet_note"] = answer.get("note")


def _apply_toilet_out(card, answer):
    card["toilet_out"] = bool(answer.get("exited"))
    if answer.get("exited"):
        # «Вышел и вернулся» — только если ВХОД тоже подтверждён моделью.
        # Отметка от датчиков («у двери») входом не является, и принимать
        # её за него значит выдумать вторую половину истории.
        card["toilet"] = "вышел и вернулся" if card.get("toilet_in") else "вышел"
    card["toilet_out_sure"] = answer.get("sure")
    card["toilet_steady"] = answer.get("steady")
    card["toilet_note"] = " | ".join(
        p for p in (card.get("toilet_note"), answer.get("note")) if p)


